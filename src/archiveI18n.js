export const isSupportedLocale = (locale) =>
  SUPPORTED_LOCALES.some((supportedLocale) => supportedLocale.id === locale);

export const getInitialLocale = () => {
  if (typeof window === "undefined") {
    return "en";
  }

  const storedLocale = window.localStorage.getItem(LOCALE_STORAGE_KEY);

  return isSupportedLocale(storedLocale) ? storedLocale : "en";
};

export const getNextLocale = (locale) => (locale === "zh" ? "en" : "zh");

export const getLocaleMeta = (locale) =>
  SUPPORTED_LOCALES.find((supportedLocale) => supportedLocale.id === locale) ??
  SUPPORTED_LOCALES[0];

const interpolate = (template, values) =>
  Object.entries(values).reduce(
    (result, [key, value]) => result.split(`{${key}}`).join(String(value)),
    template
  );

// A count picks its form: the key's _plural entry for any count but 1
// ("{count} docs"), the key itself for 1 ("{count} doc"). A locale with no
// _plural entry (Chinese has one form) uses its own entry for every count.
export const createTranslator =
  (locale) =>
  (key, values = {}) => {
    const isPlural = "count" in values && Number(values.count) !== 1;
    const lookup = (table) => (isPlural ? table?.[`${key}_plural`] : undefined) ?? table?.[key];
    const localizedValue = lookup(TRANSLATIONS[locale]) ?? lookup(TRANSLATIONS.en) ?? key;

    return interpolate(localizedValue, values);
  };
